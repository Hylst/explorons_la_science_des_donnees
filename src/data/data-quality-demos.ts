/** Indicateurs calculés sur les séjours nettoyés, avec et sans doublons */
const HOPITAL_INDICATEURS_CODE = lines(
  "# `propre` (sans doublons) et `avec_doublons` viennent du nettoyage de l'exemple précédent",
  "def indicateurs(sejours):",
  "    # Les séjours dont la date d'admission est illisible ne peuvent pas être comptés",
  "    sejours = sejours.dropna(subset=['admission', 'sortie']).sort_values(['id_patient', 'admission'])",
  "    duree = (sejours['sortie'] - sejours['admission']).dt.days",
  "    # Délai entre la sortie précédente du même patient et la nouvelle admission",
  "    delai = (sejours['admission'] - sejours.groupby('id_patient')['sortie'].shift()).dt.days",
  "    reprises = delai.between(0, 30)",
  "    return pd.Series(",
  "        {",
  "            'séjours': len(sejours),",
  "            'réadmissions sous 30 jours': int(reprises.sum()),",
  "            'taux de réadmission (%)': round(100 * reprises.mean(), 1),",
  "            'durée moyenne (jours)': round(duree.mean(), 1),",
  "        },",
  "        dtype=object,",
  "    )",
  "",
  "",
  "print(pd.DataFrame({'avec doublons': indicateurs(avec_doublons), 'sans doublons': indicateurs(propre)}))",
);

